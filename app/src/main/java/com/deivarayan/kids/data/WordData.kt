package com.deivarayan.kids.data

/**
 * One tuple per concept: an emoji picture, its category, and the word in each
 * supported language. Keeping both languages in one row guarantees the two
 * word lists stay the same size and cover the same kid-friendly concepts.
 */
private data class Concept(
    val emoji: String,
    val category: String,
    val english: String,
    val german: String,
)

object WordData {

    /** Distinct categories in the order they first appear (e.g. Animals, Food, ...). */
    val categories: List<String> by lazy { allConcepts.map { it.category }.distinct() }

    fun wordsFor(language: GameLanguage): List<WordEntry> {
        val concepts = allConcepts
        return when (language) {
            // imageQuery always uses the English term: Wikimedia Commons search
            // relevance is far better in English regardless of the displayed language.
            GameLanguage.ENGLISH -> concepts.map { WordEntry(it.english, it.emoji, it.category, it.english) }
            GameLanguage.GERMAN -> concepts.map { WordEntry(it.german, it.emoji, it.category, it.english) }
        }
    }

    /** [count] random words with distinct emoji - the tile pool for the Memory game. */
    fun randomDistinctPictures(language: GameLanguage, count: Int): List<WordEntry> =
        wordsFor(language).distinctBy { it.emoji }.shuffled().take(count)

    private fun c(emoji: String, category: String, english: String, german: String) =
        Concept(emoji, category, english, german)

